<script>
    document.addEventListener('DOMContentLoaded', function() {
        // Back to Top Button
        const backToTop = document.getElementById('backToTop');
        if (backToTop) {
            // Show/hide based on scroll position
            window.addEventListener('scroll', function() {
                if (window.pageYOffset > 300) {
                    backToTop.classList.add('show');
                } else {
                    backToTop.classList.remove('show');
                }
            });

            // Smooth scroll to top
            backToTop.addEventListener('click', function(e) {
                e.preventDefault();
                window.scrollTo({
                    top: 0,
                    behavior: 'smooth'
                });
            });
        }

        // Social Media Hover Effects
        const socialIcons = document.querySelectorAll('.social-icon');
        socialIcons.forEach(icon => {
            icon.addEventListener('mouseenter', function() {
                const platform = this.querySelector('i').className.split(' ')[1];
                let color = '';

                switch(platform) {
                    case 'fa-twitter': color = '#1DA1F2'; break;
                    case 'fa-github': color = '#333'; break;
                    case 'fa-linkedin-in': color = '#0077B5'; break;
                    case 'fa-youtube': color = '#FF0000'; break;
                    case 'fa-discord': color = '#5865F2'; break;
                    default: color = '#4e73df';
                }

                this.style.backgroundColor = color;
                this.style.color = 'white';
            });

            icon.addEventListener('mouseleave', function() {
                this.style.backgroundColor = '';
                this.style.color = '';
            });
        });

        // Link Hover Effects
        const footerLinks = document.querySelectorAll('.hover-primary');
        footerLinks.forEach(link => {
            link.addEventListener('mouseenter', function() {
                this.classList.add('text-primary');
                const icon = this.querySelector('i');
                if (icon) {
                    icon.classList.add('fa-bounce');
                }
            });

            link.addEventListener('mouseleave', function() {
                this.classList.remove('text-primary');
                const icon = this.querySelector('i');
                if (icon) {
                    icon.classList.remove('fa-bounce');
                }
            });
        });

        // Animate trust badges on scroll
        const trustBadges = document.querySelectorAll('.badge-item');
        const observer = new IntersectionObserver((entries) => {
            entries.forEach((entry, index) => {
                if (entry.isIntersecting) {
                    setTimeout(() => {
                        entry.target.style.opacity = '1';
                        entry.target.style.transform = 'translateY(0)';
                    }, index * 200);
                }
            });
        }, { threshold: 0.5 });

        trustBadges.forEach(badge => {
            badge.style.opacity = '0';
            badge.style.transform = 'translateY(20px)';
            badge.style.transition = 'all 0.5s ease';
            observer.observe(badge);
        });

        // Current Year in Copyright
        const yearSpan = document.querySelector('script');
        if (yearSpan && yearSpan.previousElementSibling) {
            // Script already handles this
        }
    });
</script>


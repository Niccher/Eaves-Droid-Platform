        <script>
            document.addEventListener('DOMContentLoaded', function() {
                // Animate stats on scroll
                const stats = document.querySelectorAll('.platform-overview h3');

                const observer = new IntersectionObserver((entries) => {
                    entries.forEach(entry => {
                        if (entry.isIntersecting) {
                            // Add animation class to stats
                            stats.forEach((stat, index) => {
                                setTimeout(() => {
                                    stat.style.animation = 'countUp 1s ease-out forwards';
                                }, index * 200);
                            });
                            observer.unobserve(entry.target);
                        }
                    });
                }, { threshold: 0.5 });

                const platformOverview = document.querySelector('.platform-overview');
                if (platformOverview) {
                    observer.observe(platformOverview);
                }

                // Add countUp animation
                const style = document.createElement('style');
                style.textContent = `
        @keyframes countUp {
            from { transform: translateY(20px); opacity: 0; }
            to { transform: translateY(0); opacity: 1; }
        }
    `;
                document.head.appendChild(style);

                // Timeline hover effects
                const timelineItems = document.querySelectorAll('.timeline-item');
                timelineItems.forEach(item => {
                    item.addEventListener('mouseenter', function() {
                        const marker = this.querySelector('.timeline-marker i');
                        if (marker) {
                            marker.style.transform = 'scale(1.2)';
                            marker.style.color = '#224abe';
                        }
                    });

                    item.addEventListener('mouseleave', function() {
                        const marker = this.querySelector('.timeline-marker i');
                        if (marker) {
                            marker.style.transform = 'scale(1)';
                            marker.style.color = '';
                        }
                    });
                });

                // Feature cards interaction
                const featureCards = document.querySelectorAll('.feature');
                featureCards.forEach(card => {
                    card.addEventListener('mouseenter', function() {
                        const icon = this.querySelector('.icon-wrapper');
                        if (icon) {
                            icon.style.transform = 'scale(1.1) rotate(5deg)';
                        }
                    });

                    card.addEventListener('mouseleave', function() {
                        const icon = this.querySelector('.icon-wrapper');
                        if (icon) {
                            icon.style.transform = '';
                        }
                    });
                });

                // Developer commitment interaction
                const commitmentItems = document.querySelectorAll('.commitment-item');
                commitmentItems.forEach(item => {
                    item.addEventListener('mouseenter', function() {
                        const icon = this.querySelector('i');
                        if (icon) {
                            icon.style.transform = 'rotate(15deg)';
                        }
                    });

                    item.addEventListener('mouseleave', function() {
                        const icon = this.querySelector('i');
                        if (icon) {
                            icon.style.transform = '';
                        }
                    });
                });
            });
        </script>